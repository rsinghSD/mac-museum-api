-- Core schema. Kept ANSI-portable so it runs on both H2 and PostgreSQL.

CREATE TABLE product_family (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug        VARCHAR(64)   NOT NULL,
    name        VARCHAR(100)  NOT NULL,
    description VARCHAR(1000) NOT NULL,
    CONSTRAINT uk_product_family_slug UNIQUE (slug)
);

CREATE TABLE apple_model (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug             VARCHAR(80)   NOT NULL,
    name             VARCHAR(120)  NOT NULL,
    release_year     INTEGER       NOT NULL,
    launch_price_usd NUMERIC(10, 2),
    family_id        BIGINT        NOT NULL,
    cpu_architecture VARCHAR(20)   NOT NULL,
    cpu_name         VARCHAR(100)  NOT NULL,
    clock_speed_mhz  INTEGER,
    base_ram_kb      INTEGER,
    summary          VARCHAR(2000) NOT NULL,
    CONSTRAINT uk_apple_model_slug UNIQUE (slug),
    CONSTRAINT fk_apple_model_family FOREIGN KEY (family_id) REFERENCES product_family (id),
    CONSTRAINT ck_apple_model_cpu_architecture CHECK (
        cpu_architecture IN ('MOS_6502', 'M68K', 'POWERPC', 'INTEL_X86', 'ARM', 'APPLE_SILICON')),
    CONSTRAINT ck_apple_model_release_year CHECK (release_year >= 1976),
    CONSTRAINT ck_apple_model_price CHECK (launch_price_usd IS NULL OR launch_price_usd >= 0)
);

CREATE INDEX ix_apple_model_release_year ON apple_model (release_year);
CREATE INDEX ix_apple_model_family_id ON apple_model (family_id);
CREATE INDEX ix_apple_model_cpu_architecture ON apple_model (cpu_architecture);
